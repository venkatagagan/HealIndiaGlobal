def _procedure(
    slug: str,
    specialty: str,
    name: str,
    description: str,
    *,
    keywords: list[str],
    body_areas: list[str],
    stay: int,
    recovery: int,
    total: int,
    price: tuple[int, int],
) -> dict[str, Any]:
    """``price`` is ``(min, max)`` in rupees; stored in paise."""
    return {
        "slug": slug,
        "specialty": specialty,
        "name": name,
        "description": description,
        "keywords": keywords,
        "body_areas": body_areas,
        "hospital_stay_days": stay,
        "recovery_days": recovery,
        "total_stay_days": total,
        "india_price_min_minor": inr(price[0]),
        "india_price_max_minor": inr(price[1]),
        "currency": "INR",
    }


