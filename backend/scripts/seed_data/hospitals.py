_GST_CHARS = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ"
_PAN_SUFFIX = "ABCDEFGHJKLMNPQRSTUVWXYZ"


def _pan(index: int, name: str) -> str:
    """Format-valid but fictional company PAN: ``AABC`` + name initial + 4 digits + letter."""
    return f"AABC{name[0].upper()}{1000 + index * 37:04d}{_PAN_SUFFIX[index % len(_PAN_SUFFIX)]}"


def gstin_for(state_code: str, pan: str) -> str:
    """GSTIN = state code + PAN + entity number + 'Z' + mod-36 check character."""
    body = f"{state_code}{pan}1Z"
    total = 0
    for i, ch in enumerate(body):
        product = _GST_CHARS.index(ch) * (1 if i % 2 == 0 else 2)
        total += product // 36 + product % 36
    return body + _GST_CHARS[(36 - total % 36) % 36]


