// Generates lib/l10n/app_localizations_overridable.dart from the gen-l10n output.
//
//   flutter gen-l10n && dart run tool/gen_l10n_overrides.dart
//
// The generated [OverridableLocalizations] wraps an [AppLocalizations] and lets an admin-edited string
// from `GET /i18n/overrides` win over the shipped ARB value (placeholders still work, see icu_format.dart).
// It extends the abstract AppLocalizations, so a stale wrapper fails `flutter analyze` / `flutter test`.
// ignore_for_file: avoid_print
import 'dart:io';

void main(List<String> args) {
  final root = args.isNotEmpty ? args.first : '.';
  final input = File('$root/lib/l10n/app_localizations.dart');
  final output = File('$root/lib/l10n/app_localizations_overridable.dart');
  if (!input.existsSync()) {
    stderr.writeln('Missing ${input.path}: run `flutter gen-l10n` first.');
    exit(1);
  }
  final source = input.readAsStringSync();
  final classStart = source.indexOf('abstract class AppLocalizations');
  final classEnd = source.indexOf('\n}\n', classStart);
  final body = source.substring(classStart, classEnd);

  final getter = RegExp(r'^  String get (\w+);$', multiLine: true);
  final method = RegExp(r'^  String (\w+)\(([^)]*)\);$', multiLine: true);

  final members = <_Member>[];
  for (final m in getter.allMatches(body)) {
    members.add(_Member(m.start, m.group(1)!, null));
  }
  for (final m in method.allMatches(body)) {
    final params = m.group(2)!.split(',').map((p) => p.trim()).where((p) => p.isNotEmpty).map((p) {
      final parts = p.split(RegExp(r'\s+'));
      return (type: parts.sublist(0, parts.length - 1).join(' '), name: parts.last);
    }).toList();
    members.add(_Member(m.start, m.group(1)!, params));
  }
  members.sort((a, b) => a.offset.compareTo(b.offset));

  final out = StringBuffer()
    ..writeln('// GENERATED by tool/gen_l10n_overrides.dart from app_localizations.dart. Do not edit by hand:')
    ..writeln('// run `flutter gen-l10n && dart run tool/gen_l10n_overrides.dart` after changing the ARB files.')
    ..writeln('// ignore_for_file: type=lint')
    ..writeln()
    ..writeln("import 'app_localizations.dart';")
    ..writeln("import 'icu_format.dart';")
    ..writeln()
    ..writeln('/// [AppLocalizations] with admin overrides (`GET /i18n/overrides`) on top of the shipped strings.')
    ..writeln('///')
    ..writeln('/// An override wins when present and renders without errors; otherwise the ARB value is used.')
    ..writeln('class OverridableLocalizations extends AppLocalizations {')
    ..writeln('  OverridableLocalizations(this.base, [this.overrides = const {}]) : super(base.localeName);')
    ..writeln()
    ..writeln('  /// The shipped (gen-l10n) strings for this locale.')
    ..writeln('  final AppLocalizations base;')
    ..writeln()
    ..writeln('  /// ARB key -> admin-edited text for this locale.')
    ..writeln('  final Map<String, String> overrides;')
    ..writeln()
    ..writeln('  String? _t(String key) {')
    ..writeln('    final o = overrides[key];')
    ..writeln('    return o == null || o.isEmpty ? null : formatIcu(o, const {}, localeName);')
    ..writeln('  }')
    ..writeln()
    ..writeln('  String? _f(String key, Map<String, Object?> args) {')
    ..writeln('    final o = overrides[key];')
    ..writeln('    return o == null || o.isEmpty ? null : formatIcu(o, args, localeName);')
    ..writeln('  }')
    ..writeln()
    ..writeln('  /// Text of a placeholder-free key, or null when [key] is unknown (used for enum labels).')
    ..writeln('  String? byKey(String key) => switch (key) {');
  for (final m in members.where((m) => m.params == null)) {
    out.writeln("    '${m.name}' => ${m.name},");
  }
  out
    ..writeln('    _ => null,')
    ..writeln('  };');
  for (final m in members) {
    out.writeln();
    out.writeln('  @override');
    if (m.params == null) {
      out.writeln("  String get ${m.name} => _t('${m.name}') ?? base.${m.name};");
    } else {
      final sig = m.params!.map((p) => '${p.type} ${p.name}').join(', ');
      final map = m.params!.map((p) => "'${p.name}': ${p.name}").join(', ');
      final call = m.params!.map((p) => p.name).join(', ');
      out.writeln("  String ${m.name}($sig) => _f('${m.name}', {$map}) ?? base.${m.name}($call);");
    }
  }
  out
    ..writeln('}')
    ..writeln()
    ..writeln('/// Every ARB key, in template order.')
    ..writeln('const List<String> kL10nKeys = [');
  for (final m in members) {
    out.writeln("  '${m.name}',");
  }
  out.writeln('];');
  output.writeAsStringSync(out.toString());
  print('Wrote ${output.path} (${members.length} keys).');
}

class _Member {
  _Member(this.offset, this.name, this.params);
  final int offset;
  final String name;
  final List<({String type, String name})>? params;
}
